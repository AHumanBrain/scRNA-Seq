#!/usr/bin/env python3

import scanpy as sc
import anndata as ad
import pandas as pd
import sys
import os
import scrublet as scr
import celltypist
from celltypist import models

sc.settings.verbosity = 3
sc.settings.figdir = './figures/'

if len(sys.argv) < 3:
    print("Error: Two input directories required (PBMC 3k and PBMC 1k).")
    sys.exit(1)

dir_3k = os.path.join(sys.argv[1], "filtered_gene_bc_matrices", "hg19")
dir_1k = os.path.join(sys.argv[2], "filtered_feature_bc_matrix")

print("Loading PBMC 3K dataset...")
adata_3k = sc.read_10x_mtx(dir_3k, var_names='gene_symbols', cache=False)
adata_3k.var_names_make_unique()
adata_3k.obs['dataset'] = 'PBMC_3k'

print("Loading PBMC 1K dataset...")
adata_1k = sc.read_10x_mtx(dir_1k, var_names='gene_symbols', cache=False)
adata_1k.var_names_make_unique()
adata_1k.obs['dataset'] = 'PBMC_1k'

# Find common genes and subset
common_genes = adata_3k.var_names.intersection(adata_1k.var_names)
adata_3k = adata_3k[:, common_genes].copy()
adata_1k = adata_1k[:, common_genes].copy()

# Concatenate datasets
adata = ad.concat([adata_3k, adata_1k], label='dataset_key', keys=['PBMC_3k', 'PBMC_1k'])
print(f"Concatenated dataset shape: {adata.shape}")

# Scrublet Doublet Detection
print("Running Scrublet doublet detection...")
sc.external.pp.scrublet(adata, batch_key='dataset_key')
sc.pl.scrublet_score_distribution(adata, save='_scrublet.png')
adata = adata[~adata.obs.predicted_doublet, :]
print(f"Cells after removing doublets: {adata.n_obs}")

# Calculate QC metrics
adata.var['mt'] = adata.var_names.str.startswith('MT-')
sc.pp.calculate_qc_metrics(adata, qc_vars=['mt'], percent_top=None, log1p=False, inplace=True)
sc.pl.violin(adata, ['n_genes_by_counts', 'total_counts', 'pct_counts_mt'], jitter=0.4, multi_panel=True, save='_qc_integrated.png')

sc.pp.filter_cells(adata, min_genes=200)
sc.pp.filter_genes(adata, min_cells=3)
adata = adata[adata.obs.n_genes_by_counts < 2500, :]
adata = adata[adata.obs.pct_counts_mt < 5, :]
print(f"Cells after QC: {adata.n_obs}")

# Normalize and log1p
sc.pp.normalize_total(adata, target_sum=1e4)
sc.pp.log1p(adata)

# Save raw unscaled for Celltypist
adata.raw = adata

# Highly variable genes
sc.pp.highly_variable_genes(adata, min_mean=0.0125, max_mean=3, min_disp=0.5, batch_key='dataset_key')
sc.pl.highly_variable_genes(adata, save='_integrated.png')
adata = adata[:, adata.var.highly_variable]

sc.pp.scale(adata, max_value=10)
sc.tl.pca(adata, svd_solver='arpack')

print("Running Harmony Integration...")
sc.external.pp.harmony_integrate(adata, 'dataset_key')

print("Computing neighbors on Harmony coordinates...")
sc.pp.neighbors(adata, n_neighbors=10, n_pcs=40, use_rep='X_pca_harmony')
sc.tl.umap(adata)
sc.pl.umap(adata, color='dataset_key', save='_integration_batch.png')

# Resolutions loop
resolutions = [0.3, 0.5, 0.8]
for res in resolutions:
    sc.tl.leiden(adata, resolution=res, key_added=f'leiden_{res}')
sc.pl.umap(adata, color=[f'leiden_{r}' for r in resolutions], save='_leiden_resolutions.png')

# Celltypist Auto Annotation
print("Running Celltypist for automated labeling...")
# Make sure model uses the correct dir inside the container (default is ~/.celltypist/data)
models.download_models(force_update=False, model=['Immune_All_Low.pkl'])
model = models.Model.load(model='Immune_All_Low.pkl')
predictions = celltypist.annotate(adata.raw.to_adata(), model=model, majority_voting=True)
adata.obs['celltypist_prediction'] = predictions.predicted_labels['predicted_labels']
adata.obs['celltypist_majority_voting'] = predictions.predicted_labels['majority_voting']

sc.pl.umap(adata, color='celltypist_majority_voting', legend_loc='on data', title='Celltypist Auto Annotation', frameon=False, save='_celltypist.png')

# Write outputs
adata.write('pbmc_integrated.h5ad')
adata.obs[['dataset_key', 'leiden_0.5', 'celltypist_majority_voting']].to_csv('cell_type_assignments.csv')
print("Analysis complete.")

